/** 这条命令在页面上叫什么；cancel 是带了 --cancel。fallback 是命令说明的第一句，没起名字时用。 */
export function stepName(command: string, cancel: boolean, fallback: string): string {
  if (!cancel) return STEPS[command] ?? fallback
  return STEPS[`${command} --cancel`] ?? `${STEPS[command] ?? fallback}（取消）`
}
